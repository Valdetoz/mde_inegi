LIMITE_SIN_CONFIRMAR = 30


class CargaMDEDialog(QtWidgets.QDialog, FORM_CLASS):
    def __init__(self, parent=None):
        """Constructor."""
        super(CargaMDEDialog, self).__init__(parent)
        self.setupUi(self)
        self.textBrowser_ayuda.setHtml(AYUDA)
        self.tarea = None
        self.capa_conectada = None
        self.carpeta_plugin = os.path.dirname(__file__)
        self.comboBox_tipo.addItems(["Terreno", "Superficie"])
        self.ruta_csv = os.path.join(self.carpeta_plugin, NOMBRE_CSV)
        self.btn_cancelar.setEnabled(False)
        self.btn_cargar_indice.clicked.connect(self.cargar_indice)
        if not os.path.exists(os.path.join(self.carpeta_plugin, NOMBRE_INDICE)):
            self.btn_cargar_indice.setEnabled(False)
            self.btn_cargar_indice.setToolTip("No encontré " + NOMBRE_INDICE + " en la carpeta del plugin")
        self.btn_salida.clicked.connect(self.elegir_salida)
        self.btn_descargar.clicked.connect(self.descargar)
        self.btn_cancelar.clicked.connect(self.cancelar)
        self.comboBox_capa_indice.currentIndexChanged.connect(self.al_cambiar_capa)
        QgsProject.instance().layersAdded.connect(self.al_cambiar_capas_del_proyecto)
        QgsProject.instance().layersRemoved.connect(self.al_cambiar_capas_del_proyecto)

    def showEvent(self, evento):
        """Se ejecuta cada vez que la ventana se muestra."""
        super(CargaMDEDialog, self).showEvent(evento)
        if self.tarea is None:
            self.textEdit_reporte.clear()
            self.progressBar.setValue(0)
        self.llenar_capas_indice()
        self.conectar_seleccion()
        self.actualizar_etiqueta()

    def cargar_indice(self):
        """Carga el índice de cartas que viene con el plugin, si no está cargado ya."""
        ruta = os.path.join(self.carpeta_plugin, NOMBRE_INDICE)
        objetivo = os.path.normcase(os.path.normpath(ruta))

        for capa in QgsProject.instance().mapLayers().values():
            fuente = capa.source().split("|")[0]
            if os.path.normcase(os.path.normpath(fuente)) == objetivo:
                self.elegir_capa_en_lista(capa.id())
                return

        capa = QgsVectorLayer(ruta, "Índice de cartas INEGI", "ogr")
        if not capa.isValid():
            self.mostrar_aviso("No pude abrir el índice de cartas.")
            return
        capa.setReadOnly(True)
        QgsProject.instance().addMapLayer(capa)
        self.elegir_capa_en_lista(capa.id())

    def elegir_capa_en_lista(self, identificador):
        self.llenar_capas_indice()
        posicion = self.comboBox_capa_indice.findData(identificador)
        if posicion != -1:
            self.comboBox_capa_indice.setCurrentIndex(posicion)
        self.conectar_seleccion()
        self.actualizar_etiqueta()

    def elegir_salida(self):
        carpeta = QtWidgets.QFileDialog.getExistingDirectory(
            self, "Seleccionar carpeta de salida")
        if carpeta:
            self.lineEdit_salida.setText(carpeta)

    def mostrar_aviso(self, texto):
        QtWidgets.QMessageBox.warning(self, "MDE INEGI", texto)

    def llenar_capas_indice(self):
        """Llena la lista con las capas de polígonos que tienen el campo cve_carta."""
        anterior = self.comboBox_capa_indice.currentData()

        candidatas = []
        for capa in QgsProject.instance().mapLayers().values():
            if not isinstance(capa, QgsVectorLayer):
                continue
            if capa.geometryType() != Qgis.GeometryType.Polygon:
                continue
            if capa.fields().lookupField(CAMPO_CLAVE) == -1:
                continue
            candidatas.append((capa.name(), capa.id()))
        candidatas.sort()

        self.comboBox_capa_indice.blockSignals(True)
        self.comboBox_capa_indice.clear()
        for nombre, identificador in candidatas:
            self.comboBox_capa_indice.addItem(nombre, identificador)
        if anterior is not None:
            posicion = self.comboBox_capa_indice.findData(anterior)
            if posicion != -1:
                self.comboBox_capa_indice.setCurrentIndex(posicion)
        self.comboBox_capa_indice.blockSignals(False)

    def capa_elegida(self):
        identificador = self.comboBox_capa_indice.currentData()
        if identificador is None:
            return None
        return QgsProject.instance().mapLayer(identificador)

    def leer_seleccion(self):
        """Devuelve (lista de claves, texto para la etiqueta)."""
        capa = self.capa_elegida()
        if capa is None:
            return None, ("No existe una capa de polígonos con el campo " + CAMPO_CLAVE +
                          ". Carga el índice de cartas.")

        indice = capa.fields().lookupField(CAMPO_CLAVE)
        claves = []
        for entidad in capa.selectedFeatures():
            valor = entidad[indice]
            if valor is None:
                continue
            clave = str(valor).strip().upper()
            if clave not in claves:
                claves.append(clave)

        return claves, "Capa: " + capa.name() + " | " + str(len(claves)) + " cartas seleccionadas"

    def actualizar_etiqueta(self, *args):
        claves, texto = self.leer_seleccion()
        self.label_seleccion.setText(texto)

    def al_cambiar_capa(self, indice=None):
        self.conectar_seleccion()
        self.actualizar_etiqueta()
        
    def al_cambiar_capas_del_proyecto(self, *args):
        """Se ejecuta cuando se cargan o se quitan capas del proyecto."""
        if not self.isVisible():
            return
        self.llenar_capas_indice()
        self.conectar_seleccion()
        self.actualizar_etiqueta()

    def conectar_seleccion(self):
        """Hace que la etiqueta se actualice cuando cambia la selección de la capa elegida."""
        if self.capa_conectada is not None:
            try:
                self.capa_conectada.selectionChanged.disconnect(self.actualizar_etiqueta)
            except (TypeError, RuntimeError):
                pass
            self.capa_conectada = None

        capa = self.capa_elegida()
        if capa is not None:
            capa.selectionChanged.connect(self.actualizar_etiqueta)
            self.capa_conectada = capa

    def descargar(self):
        carpeta_salida = self.lineEdit_salida.text().strip()
        tipo = self.comboBox_tipo.currentText()

        if not os.path.exists(self.ruta_csv):
            self.mostrar_aviso("No encontré " + NOMBRE_CSV + " en la carpeta del plugin. Reinstala el plugin.")
            return
        if carpeta_salida == "":
            self.mostrar_aviso("Elige una carpeta de salida.")
            return

        claves, texto = self.leer_seleccion()
        self.label_seleccion.setText(texto)
        if claves is None:
            self.mostrar_aviso(texto)
            return
        if len(claves) == 0:
            self.mostrar_aviso("No hay cartas seleccionadas. Selecciona al menos una en la capa del índice.")
            return

        if len(claves) > LIMITE_SIN_CONFIRMAR:
            respuesta = QtWidgets.QMessageBox.question(
                self, "MDE INEGI",
                "Hay " + str(len(claves)) + " cartas seleccionadas. ¿Quieres continuar?")
            if respuesta != QtWidgets.QMessageBox.StandardButton.Yes:
                return

        try:
            tabla = descarga.leer_tabla(self.ruta_csv)
        except Exception as error:
            self.mostrar_aviso("No pude leer el CSV: " + str(error))
            return

        self.textEdit_reporte.clear()
        self.progressBar.setMaximum(100)
        self.progressBar.setValue(0)
        self.btn_descargar.setEnabled(False)
        self.btn_cancelar.setEnabled(True)

        self.tarea = TareaDescarga(tabla, claves, tipo, carpeta_salida, self.tarea_terminada)
        self.tarea.cartaTerminada.connect(self.textEdit_reporte.appendPlainText)
        self.tarea.progressChanged.connect(self.actualizar_progreso)
        QgsApplication.taskManager().addTask(self.tarea)

    def actualizar_progreso(self, valor):
        self.progressBar.setValue(int(valor))

    def cancelar(self):
        if self.tarea is not None:
            self.tarea.cancel()
            self.textEdit_reporte.appendPlainText(
                "Cancelando... se detendrá al terminar la carta en curso.")
            self.btn_cancelar.setEnabled(False)

    def tarea_terminada(self, tarea, exito):
        self.btn_descargar.setEnabled(True)
        self.btn_cancelar.setEnabled(False)

        if exito:
            self.progressBar.setValue(100)
        else:
            self.textEdit_reporte.appendPlainText("--- Descarga cancelada o interrumpida ---")

        if self.checkBox_cargar.isChecked():
            for clave, estado, ruta in tarea.resultados:
                if ruta is None:
                    continue
                capa = QgsRasterLayer(ruta, os.path.splitext(os.path.basename(ruta))[0])
                if capa.isValid():
                    QgsProject.instance().addMapLayer(capa)

        self.tarea = None