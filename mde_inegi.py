from qgis.PyQt.QtCore import QLocale, QTranslator, QCoreApplication
from qgis.core import QgsSettings
from qgis.PyQt.QtGui import QIcon
from qgis.PyQt.QtWidgets import QMenu, QMessageBox, QToolButton
try:
    from qgis.PyQt.QtGui import QAction
except ImportError:
    from qgis.PyQt.QtWidgets import QAction

# Import the code for the dialog
from .mde_inegi_dialog import CargaMDEDialog
from .procesar_dialog import ProcesarDialog
import os.path


class CargaMDE:
    """QGIS Plugin Implementation."""

    def __init__(self, iface):
        """Constructor.

        :param iface: An interface instance that will be passed to this class
            which provides the hook by which you can manipulate the QGIS
            application at run time.
        :type iface: QgsInterface
        """
        # Save reference to the QGIS interface
        self.iface = iface
        # initialize plugin directory
        self.plugin_dir = os.path.dirname(__file__)
        # initialize locale
        locale = QgsSettings().value('locale/userLocale', QLocale().name())[0:2]
        locale_path = os.path.join(
            self.plugin_dir,
            'i18n',
            '{}.qm'.format(locale))

        if os.path.exists(locale_path):
            self.translator = QTranslator()
            self.translator.load(locale_path)
            QCoreApplication.installTranslator(self.translator)

        # Nombre del menú del plugin dentro del menú Complementos
        self.menu = self.tr(u'&MDE de INEGI')

        # Check if plugin was started the first time in current QGIS session
        # Must be set in initGui() to survive plugin reloads
        self.first_start = None
        self.dlg_procesar = None

    # noinspection PyMethodMayBeStatic
    def tr(self, message):
        """Get the translation for a string using Qt translation API.

        We implement this ourselves since we do not inherit QObject.
        """
        # noinspection PyTypeChecker,PyArgumentList,PyCallByClass
        return QCoreApplication.translate('CargaMDE', message)

    def initGui(self):
        """Create the menu entries and toolbar icons inside the QGIS GUI."""

        icon_path = os.path.join(os.path.dirname(__file__), 'icon.png')
        icono = QIcon(icon_path)
        ventana = self.iface.mainWindow()

        # Las dos herramientas, como acciones
        self.accion_descarga = QAction(
            icono, self.tr(u'Descargar MDE de INEGI'), ventana)
        self.accion_descarga.triggered.connect(self.run)

        self.accion_procesar = QAction(
            icono, self.tr(u'Procesar rásteres'), ventana)
        self.accion_procesar.triggered.connect(self.run_procesar)

        # Menú desplegable que se abrirá desde el ícono de la barra
        self.menu_desplegable = QMenu(ventana)
        self.menu_desplegable.addAction(self.accion_descarga)
        self.menu_desplegable.addAction(self.accion_procesar)

        # Botón de la barra: al hacer clic muestra el menú
        self.boton = QToolButton(ventana)
        self.boton.setIcon(icono)
        self.boton.setToolTip(self.tr(u'MDE de INEGI'))
        self.boton.setMenu(self.menu_desplegable)
        self.boton.setPopupMode(QToolButton.ToolButtonPopupMode.InstantPopup)
        self.accion_boton = self.iface.addToolBarWidget(self.boton)

        # También en el menú Complementos
        self.iface.addPluginToMenu(self.menu, self.accion_descarga)
        self.iface.addPluginToMenu(self.menu, self.accion_procesar)

        # will be set False in run()
        self.first_start = True

    def unload(self):
        """Removes the plugin menu item and icon from QGIS GUI."""
        self.iface.removePluginMenu(self.menu, self.accion_descarga)
        self.iface.removePluginMenu(self.menu, self.accion_procesar)
        self.iface.removeToolBarIcon(self.accion_boton)
        self.boton.deleteLater()
        self.menu_desplegable.deleteLater()

        for nombre in ("dlg", "dlg_procesar"):
            ventana = getattr(self, nombre, None)
            if ventana is not None:
                ventana.close()
                ventana.deleteLater()

    def run(self):
        """Herramienta 1: descarga de MDE de INEGI."""
        if self.first_start == True:
            self.first_start = False
            self.dlg = CargaMDEDialog(self.iface.mainWindow())

        self.dlg.show()
        self.dlg.raise_()
        self.dlg.activateWindow()

    def run_procesar(self):
        """Herramienta 2: procesar rásteres."""
        if self.dlg_procesar is None:
            self.dlg_procesar = ProcesarDialog(self.iface.mainWindow())

        self.dlg_procesar.show()
        self.dlg_procesar.raise_()
        self.dlg_procesar.activateWindow()